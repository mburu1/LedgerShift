-- Explicit contracts keep the serving layer independent from Spark inference.
CREATE TABLE IF NOT EXISTS MART.FACT_ORDERS (
    ORDER_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR NOT NULL,
    ORDER_TS TIMESTAMP_NTZ,
    ORDER_STATUS VARCHAR,
    TOTAL_AMOUNT NUMBER(18, 2),
    SOURCE_BATCH_ID VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS MART.FACT_PAYMENTS (
    PAYMENT_ID VARCHAR NOT NULL,
    ORDER_ID VARCHAR NOT NULL,
    PAYMENT_TS TIMESTAMP_NTZ,
    PAYMENT_STATUS VARCHAR,
    AMOUNT NUMBER(18, 2),
    SOURCE_BATCH_ID VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS MART.DIM_CUSTOMER (
    CUSTOMER_ID VARCHAR NOT NULL,
    CUSTOMER_NAME VARCHAR,
    EMAIL VARCHAR,
    VALID_FROM TIMESTAMP_NTZ,
    VALID_TO TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN,
    SOURCE_BATCH_ID VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
