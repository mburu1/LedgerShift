-- Revenue trend by day, running revenue, and month-over-month change.
CREATE OR REPLACE VIEW MART.V_DAILY_REVENUE AS
WITH daily AS (
    SELECT CAST(ORDER_TS AS DATE) AS ORDER_DATE,
           SUM(TOTAL_AMOUNT) AS REVENUE,
           COUNT(*) AS ORDER_COUNT
    FROM MART.FACT_ORDERS
    WHERE UPPER(COALESCE(ORDER_STATUS, '')) NOT IN ('CANCELLED', 'VOID')
    GROUP BY CAST(ORDER_TS AS DATE)
)
SELECT ORDER_DATE,
       REVENUE,
       ORDER_COUNT,
       SUM(REVENUE) OVER (
           ORDER BY ORDER_DATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS RUNNING_REVENUE,
       LAG(REVENUE) OVER (ORDER BY ORDER_DATE) AS PREVIOUS_DAY_REVENUE
FROM daily;

CREATE OR REPLACE VIEW MART.V_CUSTOMER_REVENUE_RANK AS
SELECT CUSTOMER_ID,
       SUM(TOTAL_AMOUNT) AS LIFETIME_REVENUE,
       RANK() OVER (ORDER BY SUM(TOTAL_AMOUNT) DESC) AS REVENUE_RANK
FROM MART.FACT_ORDERS
WHERE UPPER(COALESCE(ORDER_STATUS, '')) NOT IN ('CANCELLED', 'VOID')
GROUP BY CUSTOMER_ID;

CREATE OR REPLACE VIEW MART.V_MONTHLY_REVENUE AS
WITH monthly AS (
    SELECT DATE_TRUNC('MONTH', ORDER_TS)::DATE AS REVENUE_MONTH,
           SUM(TOTAL_AMOUNT) AS REVENUE
    FROM MART.FACT_ORDERS
    WHERE UPPER(COALESCE(ORDER_STATUS, '')) NOT IN ('CANCELLED', 'VOID')
    GROUP BY DATE_TRUNC('MONTH', ORDER_TS)::DATE
)
SELECT REVENUE_MONTH,
       REVENUE,
       LAG(REVENUE) OVER (ORDER BY REVENUE_MONTH) AS PRIOR_MONTH_REVENUE,
       REVENUE - LAG(REVENUE) OVER (ORDER BY REVENUE_MONTH) AS MONTH_OVER_MONTH_DELTA
FROM monthly;
